/*
 * The R5900 interpreter for the disc's MIPS programs (port/src/mips/,
 * docs/web_port.md phase 4).
 *
 * 486 programs on the disc are MIPS code that the game loads at fixed EE
 * addresses and runs as native code: the character programs of
 * SYS/GBX.PAC (party slots 0x708000-0x727FFF, enemy slots 0x728000-
 * 0x747FFF, 0x8000 each) and the magic and skill programs of
 * BTL_DATA/ *.DAT (0x748000). They call 225 functions of the main
 * executable and BATTLE by address, use their globals by address
 * (config/abi_main.txt, config/abi_battle.txt), and store their own code
 * addresses into the game's function pointers (BtlCharDef.init/attack/
 * validate, MgcWork.update/partStart/nextPart/draw, ...).
 *
 * Memory. The load areas are one host buffer, the window, that stands for
 * EE 0x708000-0x74FFFF. The programs' own constants are EE addresses (of
 * their own code and data, and of the ABI globals); the port's objects
 * live at host addresses. So a value can be in two forms:
 *
 *   EE form    an address in the window's EE range, or inside one of the
 *              ABI globals' EE ranges, or a program code address;
 *   host form  the same place at its host address (the window's buffer,
 *              the port's object), and for code a native thunk.
 *
 * Registers hold the EE form, memory the host form, so that both the
 * program's own address arithmetic and comparisons (`u - btlUnits`,
 * `u == &btlUnits[4]`) and the port's C reading what the program stored
 * work. The interpreter converts at the boundary:
 *
 *   - a 32-bit word stored with sw/sd/sq (each word of it) goes to host
 *     form, and one loaded with lw/ld/lq to EE form (code addresses only
 *     become thunks outside the MIPS stack); only 4-aligned values are
 *     converted, since only those can be the pointers in question;
 *   - pointer arguments of the bridged functions go to host form, pointer
 *     results come back in EE form (any alignment);
 *   - arguments from native callers (grx_mips_call, thunks) go to EE form,
 *     the result back to host form.
 *
 * When a program is entered at the start of its area, the pointer words
 * in its data (after its code) are converted to host form once, so the
 * port's C can read pointers in program data it was handed (BtlChrData's
 * tables in a GBX program).
 *
 * Code. A jump to an address outside the window is a call of native code:
 * an ABI function (by its EE address) runs its bridge handler, a thunk
 * goes back to its MIPS address, a host function the bridge knows runs its
 * handler; then execution goes on at $ra. Native code calls MIPS code
 * through grx_mips_call()/grx_mips_callv() or a thunk; those calls nest.
 */
#ifndef GRX_MIPS_H
#define GRX_MIPS_H

#include <stddef.h>
#include <stdint.h>

/* The load areas */
#define GRX_MIPS_WIN_EE    0x00708000u
#define GRX_MIPS_WIN_SIZE  0x00048000u
#define GRX_MIPS_AREA_SIZE 0x00008000u
#define GRX_MIPS_NAREAS    9
#define GRX_MIPS_PARTY_EE  0x00708000u /* btlPartyGbx0-3 */
#define GRX_MIPS_ENEMY_EE  0x00728000u /* btlEnemyGbx0-3 */
#define GRX_MIPS_MAGIC_EE  0x00748000u /* func_00748000 (MAGIC_PROG_VRAM) */

/* Where main and BATTLE were in EE memory: an EE address here that isn't
   an ABI global is an error, when the host has nothing there either */
#define GRX_MIPS_EE_LOW  0x00400000u
#define GRX_MIPS_EE_HIGH 0x00760000u

/* ra of a call from native code: returning there ends the call */
#define GRX_MIPS_RETURN 0xFFFFFFF0u

typedef union GrxMipsReg {
    uint64_t d[2];
    int64_t sd[2];
    uint32_t w[4];
    int32_t sw[4];
} GrxMipsReg;

typedef union GrxMipsFpr {
    float f;
    uint32_t u;
    int32_t i;
} GrxMipsFpr;

struct GrxMipsAbiFunc;

typedef struct GrxMipsCpu {
    GrxMipsReg r[32];
    uint64_t lo, hi, lo1, hi1; /* LO/HI; LO1/HI1 are their upper halves (MMI) */
    GrxMipsFpr f[32];
    GrxMipsFpr facc; /* the FPU's ACC (madd.s, ...) */
    int fcc;         /* FCR31 C */
    uint32_t pc, npc;
    uint64_t steps;  /* instructions run since the outermost call began */
    const struct GrxMipsAbiFunc *cur; /* the bridged function being called */
} GrxMipsCpu;

/* ------------------------------------------------------------------ ABI
   Tables generated by port/tools/gen_mips_bridge.py (abi_gen.c), sorted
   by address. sig: "<result>:<params>", one letter each: v void, p pointer,
   f float, d double (soft-float, one 64-bit GPR), l 64-bit integer,
   b s8, B u8, h s16, H u16, i s32, I u32, . varargs */
typedef struct GrxMipsAbiFunc {
    uint32_t addr;
    const char *name;
    const char *sig;
} GrxMipsAbiFunc;

typedef struct GrxMipsAbiData {
    uint32_t ee;
    uint32_t size;
    const char *name;
} GrxMipsAbiData;

extern const GrxMipsAbiFunc grx_mips_abi_funcs[];
extern const int grx_mips_abi_nfuncs;
extern const GrxMipsAbiData grx_mips_abi_data[];
extern const int grx_mips_abi_ndata;

/* A bridged call: read the arguments from c, call, write the result */
typedef void (*GrxMipsHandler)(GrxMipsCpu *c, const GrxMipsAbiFunc *f);

/* Arguments and results for handlers. n counts integer-class arguments
   ($a0-$a3, $t0-$t3) and float arguments ($f12-$f19) separately, as the
   EABI does */
int32_t grx_mips_arg_i(GrxMipsCpu *c, int n);
void *grx_mips_arg_p(GrxMipsCpu *c, int n);  /* converted to host form */
int32_t grx_mips_arg_v(GrxMipsCpu *c, int n); /* a variadic word (host form if it's an address) */
int64_t grx_mips_arg_l(GrxMipsCpu *c, int n);
double grx_mips_arg_d(GrxMipsCpu *c, int n);
float grx_mips_arg_f(GrxMipsCpu *c, int n);
void grx_mips_ret_i(GrxMipsCpu *c, int32_t v);
void grx_mips_ret_p(GrxMipsCpu *c, const void *p); /* converted to EE form */
void grx_mips_ret_l(GrxMipsCpu *c, int64_t v);
void grx_mips_ret_d(GrxMipsCpu *c, double v);
void grx_mips_ret_f(GrxMipsCpu *c, float v);

/* The interpreter's own versions of a few ABI functions (builtins.c): the
   soft-float double helpers, and VU0 helpers the port has no C for */
void grx_mips_bi_dpadd(GrxMipsCpu *c, const GrxMipsAbiFunc *f);
void grx_mips_bi_dpsub(GrxMipsCpu *c, const GrxMipsAbiFunc *f);
void grx_mips_bi_dpmul(GrxMipsCpu *c, const GrxMipsAbiFunc *f);
void grx_mips_bi_litodp(GrxMipsCpu *c, const GrxMipsAbiFunc *f);
void grx_mips_bi_dptoli(GrxMipsCpu *c, const GrxMipsAbiFunc *f);
void grx_mips_bi_dptofp(GrxMipsCpu *c, const GrxMipsAbiFunc *f);
void grx_mips_bi_fptodp(GrxMipsCpu *c, const GrxMipsAbiFunc *f);
void grx_mips_bi_VuBezierInterp(GrxMipsCpu *c, const GrxMipsAbiFunc *f);
void grx_mips_bi_VuVecNormalizeRcpLen(GrxMipsCpu *c, const GrxMipsAbiFunc *f);
/* name -> builtin handler, or 0 */
GrxMipsHandler grx_mips_builtin(const char *name);

/* ------------------------------------------------------------------ setup */

/* The memory the interpreter runs in: the window (GRX_MIPS_WIN_SIZE bytes,
   16-aligned, zeroed), the MIPS stack, and whether EE addresses between
   GRX_MIPS_EE_LOW and GRX_MIPS_EE_HIGH that aren't ABI globals are errors
   (strict: nothing of the host's is there). Neither buffer may overlap
   GRX_MIPS_EE_LOW..GRX_MIPS_EE_HIGH. Called once. */
void grx_mips_setup(void *window, void *stack, uint32_t stack_size, int strict);
int grx_mips_ready(void);

/* The bridge: per entry of grx_mips_abi_funcs a handler (0: none; calling
   it stops the game) and the native function's address (0: none), and
   per entry of grx_mips_abi_data the port's object. The tables must stay
   valid. */
void grx_mips_set_bridge(const GrxMipsHandler *handlers, void *const *func_hosts, void *const *data_hosts);
/* The generated one (bridge_gen.c; the tests have their own) */
void grx_mips_install_bridge(void);

/* ------------------------------------------------------------------ use */

/* Host address of an EE address in the window */
void *grx_mips_area(uint32_t ee);
/* The area holding ee now holds a program of size bytes (0: unknown);
   call it whenever one is copied or read there */
void grx_mips_area_loaded(uint32_t ee, uint32_t size);

/* Run MIPS code at addr (EE form, a host window address or a thunk) with
   up to 8 integer arguments (host form; converted to EE form). Returns
   $v0, converted to host form. Calls nest. */
uint32_t grx_mips_callv(uint32_t addr, const uint32_t *args, int nargs);
/* The same, with the result's raw 64-bit $v0 and $f0 */
uint64_t grx_mips_callv_raw(uint32_t addr, const uint32_t *args, int nargs, float *f0);

/* Form conversions of a 32-bit value (see above); the _any versions
   don't require 4-alignment */
uint32_t grx_mips_to_host(uint32_t v);
uint32_t grx_mips_to_host_any(uint32_t v);
uint32_t grx_mips_to_ee(uint32_t v);
uint32_t grx_mips_to_ee_any(uint32_t v);
/* The thunk for a MIPS code address (EE form): a native function that
   runs it, taking up to 8 int arguments and returning $v0 */
void *grx_mips_thunk(uint32_t ee);
/* The MIPS address of a thunk, or 0 if p isn't one */
uint32_t grx_mips_thunk_target(const void *p);

/* Host pointer for an EE-form address the program accesses (size bytes) */
void *grx_mips_mem(uint32_t addr, uint32_t size);

/* The CPU (one; nested calls save and restore it) */
GrxMipsCpu *grx_mips_cpu(void);

/* Code end of an area's program (from the start of its data, as
   tools/abi_scan.py finds it), once it has been entered */
uint32_t grx_mips_code_end(uint32_t ee);

/* Debugging and tests */
extern uint64_t grx_mips_step_limit;  /* stop after this many instructions in one outermost call (0: no limit) */
extern int grx_mips_log_calls;        /* log every bridged call */
extern int grx_mips_check_code;       /* stop when execution leaves an area's code */
/* If set, accesses below 0x10000 (null pointers) go to this buffer of
   0x10010 bytes instead of stopping: tests running programs on empty game
   state */
extern uint8_t *grx_mips_null_page;
/* If set, says whether a host address the program accesses is memory
   (tests: a wild pointer stops the program instead of the process) */
extern int (*grx_mips_host_check)(uint32_t addr);
/* Forget the calls in progress, after a grx_fatal() that a test caught
   with longjmp */
void grx_mips_abandon(void);
/* One instruction as text */
const char *grx_mips_disasm(uint32_t word, uint32_t pc, char *buf, size_t n);
/* Name of the ABI function or global at/around an EE address, for messages */
const char *grx_mips_describe(uint32_t ee, char *buf, size_t n);

#endif

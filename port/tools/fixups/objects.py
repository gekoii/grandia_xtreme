"""Objects that rely on their neighbours (port/README.md; the cases are in
build/port/object_audit.txt, from port/tools/object_audit.py).

The matching build keeps every object at its original address, and some
of the game's code reaches from one object into the next: save.h's
SysSaveData (0x3300 bytes) over sysSaveData (0x1A18), ptyCharStatsBuf,
evtMainFlag, ...; sys.h's SysState (0x1400) over sysState and the font
images after it; FldMenuItem (0xE8) over fldMenuItem (0x10) and
fldMenuItemCursor. clang and lld don't promise the original order, so
here the objects the code treats as one block become one definition, with
every name an alias (`.set`) at its original offset.

**The .bss and .scommon files** (src/<binary>/bss_*.c, generated by
tools/gen_bss.py: every uninitialized object of a binary in address order,
with its address in a comment). Every case the audit finds in the game's
own objects is there (60 groups of objects), so each file becomes one byte
block of its section's size, aligned like its first object, and each
object's name a global alias at its address minus the section's start.
That keeps every distance the game relies on within each section,
including the accesses the audit can't see (indexes in variables,
pointers carried along). The names the linker defines relative to these
objects (syms.py: `sysSavePlayTime = sysSaveData + 0x1C`) become `.set`s
on these aliases, in the same file. A .scommon file and the .bss file
after it are separate blocks: nothing reaches from one to the other.

On x86-64 (port/docs/win64.md) a slot is the PS2's size, so an object
whose type is bigger there (a pointer, a struct holding pointers) would
run into its neighbour. Those (bss64.json, from port/tools/gen_bss64.py,
by sizeof in the game's own declarations) are their own objects there,
and their slots stay unused; every other object keeps its offset.

Initialized data needs nothing here so far: the audit's remaining cases
are library data the host replaces and one table in port/game/ (see the
report). If one turns up, the fix is the same idea in the data file's
generated copy: the run of objects as one struct that keeps their types
and initializers, padded to the original offsets, with the names as
aliases of its members.

Also here: locals the code writes past (GphPrimSecondTick, OccAlphaUpdate),
from the -Warray-bounds list at the end of the report and the x86-64 build.

BLOCKS lists every range made one block, for object_audit.py's report:
{"name", "lo", "hi"} with original addresses.
"""

import json
import os
import re

_ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))

# The objects bigger on x86-64 than their PS2 slot (port/tools/gen_bss64.py
# writes it): {bss file: {name: x86-64 size}}
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "bss64.json")) as _f:
    _BSS64 = json.load(_f)["bss"]

FIXUPS = {}
BLOCKS = []

# ---------------------------------------------------------------------------
# 1. The .bss and .scommon files

BSS_FILES = [
    "src/main/bss_4A9410.c",
    "src/main/bss_4A9680.c",
    "src/field/bss_6762B8.c",
    "src/field/bss_676480.c",
    "src/battle/bss_6E3E80.c",
    "src/battle/bss_6E3F00.c",
    "src/viewer/bss_703500.c",
]

# One definition as tools/gen_bss.py writes it
_BSS_DEF = r"(u8|u16|u32) (\w+)(?:\[(0x[0-9A-F]+)\])? BSS(?: ALIGN\((\d+)\))?; /\* ([0-9A-F]{8})\b[^\n]*\*/\n"
_BSS_RUN = "(?m)^(?:" + _BSS_DEF + ")+"
_BSS_RANGE = re.compile(r"0x([0-9A-F]{8})-0x([0-9A-F]{8})")
_SIZES = {"u8": 1, "u16": 2, "u32": 4}


def _bss_block(rel, text):
    """The replacement for a bss file's run of definitions: one block and
    the aliases"""
    m = _BSS_RANGE.search(text[:text.index("*/")])
    sec_lo, sec_hi = int(m.group(1), 16), int(m.group(2), 16)
    tag = os.path.basename(rel)[:-2]
    block = f"grx_{os.path.dirname(rel).split('/')[-1]}_{tag}"
    defs = []
    for d in re.finditer(_BSS_DEF, text):
        typ, name, count, align, addr = d.groups()
        size = _SIZES[typ] * (int(count, 16) if count else 1)
        defs.append((name, int(addr, 16), size, int(align) if align else _SIZES[typ]))
    if not defs or defs[0][1] != sec_lo:
        raise RuntimeError(f"{rel}: the first object isn't at the section's start 0x{sec_lo:08X}")
    end = max(sec_hi, max(a + s for _, a, s, _ in defs))
    align = defs[0][3]
    prev_end = sec_lo
    for name, addr, size, al in defs:
        if addr < prev_end or (addr - sec_lo) % min(al, align):
            raise RuntimeError(f"{rel}: {name} at 0x{addr:08X} overlaps or is misaligned")
        prev_end = addr + size
    out = [f"/* port: every object of this section in one block, each name an alias at its\n"
           f"   original offset (port/tools/fixups/objects.py). GRX_SYM is a C name\n"
           f"   in assembly: with the target's prefix (clang's __USER_LABEL_PREFIX__,\n"
           f"   _ on i686, none on x86-64) */\n",
           "#define GRX_SYM_STR_(x) #x\n",
           "#define GRX_SYM_STR(x) GRX_SYM_STR_(x)\n",
           "#define GRX_SYM(n) GRX_SYM_STR(__USER_LABEL_PREFIX__) #n\n",
           f"u8 {block}[0x{end - sec_lo:X}] BSS ALIGN({align});\n"]
    big = _BSS64.get(rel, {})
    for name, addr, size, _ in defs:
        alias = (f'__asm__(".globl " GRX_SYM({name}) "\\n.set " GRX_SYM({name}) ", " GRX_SYM({block}) '
                 f'"+0x{addr - sec_lo:X}"); /* {addr:08X}, 0x{size:X} */\n')
        if name in big:
            # Bigger on x86-64 than its slot (a pointer, or a struct with
            # pointers; bss64.json): its own object there, the slot unused
            out.append(f"#if __SIZEOF_POINTER__ == 4\n{alias}#else\n"
                       f"u8 {name}[0x{big[name]:X}] BSS ALIGN(16); /* {addr:08X}, 0x{size:X} on the PS2 */\n#endif\n")
        else:
            out.append(alias)
    BLOCKS.append({"name": f"{rel} as {block}", "lo": sec_lo, "hi": end})
    return "".join(out)


def _bss_fixup(rel):
    with open(os.path.join(_ROOT, rel), encoding="latin-1") as f:
        text = f.read()
    runs = list(re.finditer(_BSS_RUN, text))
    if len(runs) != 1 or len(re.findall(_BSS_DEF, text)) != len(re.findall(_BSS_DEF, runs[0].group(0))):
        raise RuntimeError(f"{rel}: the definitions aren't one run of lines (port/tools/fixups/objects.py)")
    rep = _bss_block(rel, text)
    return [(_BSS_RUN, lambda m: rep)]


for _rel in BSS_FILES:
    FIXUPS[_rel] = _bss_fixup(_rel)

# ---------------------------------------------------------------------------
# 2. Locals the code writes past (clang -Warray-bounds, in the report)

# GphPrimSecondTick fills a[0..7] of an f32 a[4] it never reads (on the EE
# the stores land in its frame's padding); on x86 they would run over the
# stack, so the array gets the 8 slots the code uses
FIXUPS.setdefault("src/main/43C630.c", []).append(
    (r"(void GphPrimSecondTick\(void\) \{\n    f32 a\[)4(\];\n)", r"\g<1>8\2"))

# OccAlphaUpdate passes one f32 (&val) to OccInterpVec, which writes a
# VuVec3 (x, y, z): the y and z stores run over its frame (on the EE and
# i686 into something unused, on x86-64 into the saved registers). It
# gets the three floats and keeps x.
FIXUPS.setdefault("src/field/5BA330.c", []).append(
    (r"OccInterpVec\(o, &val\);", "{ f32 grx_v[3]; OccInterpVec(o, (void *)grx_v); val = grx_v[0]; }"))

#!/usr/bin/env python3
"""Regenerate a binary's .text and .rodata subsegments from src/<binary>/*.c.

Usage: update_segments.py [binary]   (main, field, battle, viewer; default main)

Every C file in src/<binary>/ holds one or more functions that are adjacent in
the binary. Each file becomes a `c` subsegment covering its functions, and
the code between them stays `asm`. If the file's functions use jump tables
(switch statements), the tables' range in .rodata becomes a `.rodata`
subsegment for the same file, so the compiled tables land at the original
address. A `/* rodata: 0xSTART-0xEND */` marker (see compile_c.py) claims an
explicit range instead, for constants and strings. The lists are written between the BEGIN/END markers in
the binary's splat config (see tools/binaries.py). Run tools/split.sh afterwards.

Data-only C files (src/<binary>/data/<ADDR>.c, plan step 6b) claim ranges of
.data and/or .rodata with `/* data: 0xSTART-0xEND */` / `/* rodata: ... */`
markers (tools/data_asm.py): they become `.data` subsegments in the data
block and `.rodata` subsegments in the rodata block, and the rest stays asm.
"""
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from compile_c import owned_rodata  # noqa: E402
from data_asm import markers as data_markers  # noqa: E402

from binaries import BINARIES  # noqa: E402

JR_RA = 0x03E00008


def is_final_jump(word):
    """`jr ra` or a `j` (tail call): an instruction a function can end with."""
    return word == JR_RA or word >> 26 == 2

DEF_RE = re.compile(r"^[A-Za-z_].*?\b(\w+)\(.*\)\s*\{\s*$", re.M)


def named_functions():
    """Functions with real names (config/symbol_addrs*.txt) -> address."""
    out = {}
    for path in sorted(glob.glob("config/symbol_addrs*.txt")):
        for m in re.finditer(r"^(\w+)\s*=\s*0x([0-9A-Fa-f]+);\s*//\s*type:func", open(path).read(), re.M):
            out[m.group(1)] = int(m.group(2), 16)
    return out


def defined_functions(text, names):
    """Addresses of the functions a C file defines: func_XXXXXXXX or a known name."""
    addrs = []
    for name in DEF_RE.findall(text):
        if re.fullmatch(r"func_[0-9A-F]{8}", name):
            addrs.append(int(name[5:], 16))
        elif name in names:
            addrs.append(names[name])
    return addrs


def code_end(rom, func, end):
    """End of the code in [func, end), leaving out trailing zero padding."""
    words = [int.from_bytes(rom[o:o + 4], "little") for o in range(func, end, 4)]
    # The code ends with a final jump (`jr ra`, or `j` for a tail call) and
    # its delay slot; the delay slot may itself be a zero `nop`.
    last = max((i for i, w in enumerate(words) if w), default=None)
    if last is None:
        return end
    if is_final_jump(words[last]):
        stop = last + 2
    elif last >= 1 and is_final_jump(words[last - 1]):
        stop = last + 1
    else:
        return end
    if stop >= len(words):
        return end
    code = func + stop * 4
    # The next piece is aligned to its address's natural alignment (see the
    # Makefile); only padding that alignment won't recreate needs a piece.
    align = next(a for a in (16, 8, 4, 1) if end % a == 0)
    return end if -(-code // align) * align == end else code


def markers(what):
    return (f"      # BEGIN {what} subsegments (generated by tools/update_segments.py)\n",
            f"      # END {what} subsegments\n")


def natural(addr):
    return next(a for a in (16, 8, 4, 2, 1) if addr % a == 0)


def layout(pieces, start, end, gap_type, prefix, rom=None):
    """Subsegment lines for [start, end): the given pieces, gap_type in between.
    With rom: a gap of zeros before a data C file (src/<binary>/data/) that
    the file's alignment recreates (the Makefile aligns it to its address) is
    left out instead of becoming a piece of its own. So is an 8-aligned gap
    of zeros before a code file's .rodata (16-aligned jump tables, or a
    `/* rodata: */` claim the Makefile aligns): padding where a data file
    would otherwise be; the zero words at 4 mod 8 after a C file's .rodata
    stay asm pieces."""
    lines, pos = [], start
    for p_start, p_end, kind, name in sorted(pieces):
        if p_start < pos:
            raise SystemExit(f"{name}: overlaps the previous subsegment at 0x{pos:06X}")
        if p_start > pos and rom is not None and pos > start and \
                ("/data/" in name or (kind == ".rodata" and pos % 8 == 0)) and \
                not any(rom[pos:p_start]) and -(-pos // natural(p_start)) * natural(p_start) == p_start:
            pos = p_start
        if p_start > pos:
            lines.append(f"      - [0x{pos:06X}, {gap_type}, {prefix}/{pos:06X}]\n")
        lines.append(f"      - [0x{p_start:06X}, {kind}, {name}]\n")
        pos = p_end
    if pos < end:
        lines.append(f"      - [0x{pos:06X}, {gap_type}, {prefix}/{pos:06X}]\n")
    return lines


def replace_block(text, what, lines):
    begin, end = markers(what)
    head, rest = text.split(begin)
    _, tail = rest.split(end)
    return head + begin + "".join(lines) + end + tail


def main():
    os.chdir(os.path.join(os.path.dirname(__file__), ".."))
    binary = BINARIES[sys.argv[1] if len(sys.argv) > 1 else "main"]
    name, VRAM, TEXT_END = binary["name"], binary["vram"], binary["text_end"]
    RODATA_START, RODATA_END = binary["rodata"]
    FUNCTIONS, JTBLS, CONFIG = binary["functions"], binary["jtbls"], binary["config"]
    SRC = binary["src"]
    starts = {int(line, 16) - VRAM for line in open(FUNCTIONS) if line.strip()}
    tables = {}  # function rom offset -> [(table rom offset, size)]
    for line in (open(JTBLS) if os.path.exists(JTBLS) else []):
        if line.strip() and not line.startswith("#"):
            func, addr, size = line.split()
            tables.setdefault(int(func, 16) - VRAM, []).append((int(addr, 16) - VRAM, int(size, 16)))

    rom = open(binary["rom"], "rb").read()
    names = named_functions()
    c_files = []
    for path in glob.glob(f"{SRC}/*.c"):
        funcs = sorted(a - VRAM for a in defined_functions(open(path).read(), names))
        if funcs:
            c_files.append((funcs, os.path.splitext(os.path.basename(path))[0]))
            missing = set(funcs) - starts
            if missing:
                raise SystemExit(f"{path}: not in {FUNCTIONS}: {sorted(hex(a + VRAM) for a in missing)}")
    starts = sorted(starts)

    text_pieces, rodata_pieces = [], []
    for funcs, stem in c_files:
        first = starts.index(funcs[0])
        if starts[first:first + len(funcs)] != funcs:
            raise SystemExit(f"{SRC}/{stem}.c: its functions are not adjacent in the binary")
        after = first + len(funcs)
        end = starts[after] if after < len(starts) else TEXT_END
        # Zero words after the last function's final `jr ra` and its delay
        # slot are padding, not code: the compiled C doesn't emit them. When
        # the next piece's alignment won't restore them, they become an asm
        # piece of their own.
        end = code_end(rom, funcs[-1], end)
        text_pieces.append((funcs[0], end, "c", f"{name}/{stem}"))

        file_tables = sorted(t for f in funcs for t in tables.get(f, []))
        owned = owned_rodata(open(f"{SRC}/{stem}.c").read())
        if owned:
            # The file claims an explicit range (constants, strings, tables)
            start, end = owned[0] - VRAM, owned[1] - VRAM
            if not RODATA_START <= start < end <= RODATA_END:
                raise SystemExit(f"{SRC}/{stem}.c: rodata marker is outside .rodata")
            for a, size in file_tables:
                if not start <= a and a + size <= end:
                    raise SystemExit(f"{SRC}/{stem}.c: rodata marker doesn't cover its jump table at 0x{a + VRAM:X}")
            rodata_pieces.append((start, end, ".rodata", f"{name}/{stem}"))
        elif file_tables:
            # The compiler emits a file's tables back to back, each 16-aligned
            for (a, size), (b, _) in zip(file_tables, file_tables[1:]):
                if b != (a + size + 15) & ~15:
                    raise SystemExit(f"{SRC}/{stem}.c: its jump tables are not contiguous in .rodata")
            last, last_size = file_tables[-1]
            rodata_pieces.append((file_tables[0][0], last + last_size, ".rodata", f"{name}/{stem}"))

    # Data-only C files: their .data and .rodata ranges
    data_pieces = []
    n_data_files = 0
    for path in sorted(glob.glob(f"{SRC}/data/*.c")):
        stem = os.path.splitext(os.path.basename(path))[0]
        try:
            claims = data_markers(open(path).read())
        except ValueError as e:
            raise SystemExit(f"{path}: {e}")
        if not claims:
            raise SystemExit(f"{path}: no /* data: */ or /* rodata: */ marker")
        first = min(s for s, _ in claims.values())
        if stem != f"{first:06X}" and stem != f"{first:08X}":
            raise SystemExit(f"{path}: should be named after its first range's start, {first:06X}.c")
        n_data_files += 1
        for sec, (start, end) in claims.items():
            start, end = start - VRAM, end - VRAM
            if sec == ".rodata":
                if not RODATA_START <= start < end <= RODATA_END:
                    raise SystemExit(f"{path}: rodata marker is outside .rodata")
                rodata_pieces.append((start, end, ".rodata", f"{name}/data/{stem}"))
            else:
                if not binary.get("data") or not binary["data"][0] <= start < end <= binary["data"][1]:
                    raise SystemExit(f"{path}: data marker is outside .data")
                data_pieces.append((start, end, ".data", f"{name}/data/{stem}"))

    text = open(CONFIG).read()
    text = replace_block(text, "text", layout(text_pieces, 0, TEXT_END, "asm", name))
    text = replace_block(text, "rodata", layout(rodata_pieces, RODATA_START, RODATA_END, "rodata", name, rom))
    if binary.get("data"):
        text = replace_block(text, "data", layout(data_pieces, *binary["data"], "data", name, rom))
    open(CONFIG, "w").write(text)
    print(f"{len(text_pieces)} c subsegments in .text, {len(rodata_pieces)} .rodata subsegments "
          f"(jump tables, constants, data files), {len(data_pieces)} .data subsegments "
          f"({n_data_files} data files)")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Collect every function signature the project knows, as context for m2c.

Signatures come from src/*/*.c (every binary): function definitions are authoritative,
and extern declarations of not-yet-decompiled callees (which were verified by
the caller matching) are used by majority vote. Project-specific types are
reduced to what m2c can parse: struct/typedef pointers become `void *`,
by-value unknown types become `s32`.

Writes build/m2c/known_functions.h, which tools/m2c_batch.py appends to its
m2c context so drafts start with the right argument counts and return types.
"""
import collections
import glob
import os
import re

OUT = "build/m2c/known_functions.h"
BASIC = {"void", "char", "short", "int", "long", "float", "double", "signed", "unsigned",
         "s8", "u8", "s16", "u16", "s32", "u32", "s64", "u64", "f32", "const", "volatile"}
SIG_RE = re.compile(
    r"^(?:extern\s+|static\s+)?([A-Za-z_][\w\s\*]*?)\s*\b(\w+)\s*\(([^()]*)\)\s*([;{])", re.M)


def named_functions():
    names = set()
    text = "".join(open(p).read() for p in sorted(glob.glob("config/symbol_addrs*.txt")))
    for m in re.finditer(r"^(\w+)\s*=\s*0x[0-9A-Fa-f]+;\s*//\s*type:func", text, re.M):
        names.add(m.group(1))
    return names


def simplify_type(t):
    """'const Foo *' -> 'void *', 'Foo' -> 's32', 'u16' -> 'u16'."""
    t = " ".join(t.replace("*", " * ").split())
    stars = t.count("*")
    words = [w for w in t.replace("*", " ").split() if w not in ("const", "volatile", "struct", "union", "enum")]
    if words and all(w in BASIC for w in words):
        base = " ".join(words)
    elif stars:
        base, stars = "void", stars
    else:
        base = "s32"
    if base == "void" and stars:
        return "void " + "*" * stars
    return base + (" " + "*" * stars if stars else "")


def simplify_params(params):
    params = params.strip()
    if params in ("", "void"):
        return "void"
    out = []
    for p in params.split(","):
        p = p.strip()
        if p == "...":
            out.append("...")
            continue
        p = re.sub(r"\[\s*\w*\s*\]", "*", p)          # arrays decay to pointers
        m = re.match(r"(.*?)(\b\w+)?\s*$", p)
        t = m.group(1) if m.group(2) and m.group(1).strip() else p
        out.append(simplify_type(t))
    return ", ".join(out)


def main():
    os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    names = named_functions()
    defs, decls = {}, collections.defaultdict(collections.Counter)
    for path in sorted(glob.glob("src/*/*.c")):
        text = re.sub(r"/\*.*?\*/", "", open(path).read(), flags=re.S)
        for ret, name, params, end in SIG_RE.findall(text):
            if not (re.fullmatch(r"func_[0-9A-F]{8}", name) or name in names):
                continue
            if "M2C_" in ret + params or ret.strip() in ("return", "else"):
                continue
            sig = (simplify_type(ret), simplify_params(params))
            if end == "{":
                defs[name] = sig
            else:
                decls[name][sig] += 1

    sigs = dict(defs)
    for name, votes in decls.items():
        if name not in sigs:
            sigs[name] = votes.most_common(1)[0][0]

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("/* Generated by tools/make_m2c_context.py: known function signatures for m2c */\n")
        for name in sorted(sigs):
            ret, params = sigs[name]
            f.write(f"{ret} {name}({params});\n")
    print(f"{len(sigs)} signatures ({len(defs)} from definitions) -> {OUT}")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Write config/jtbls.<binary>.txt: which function owns which jump table.

Usage: make_jtbl_index.py [binary]   (main, field, battle or viewer; default main)


Each line is `<function> <table address> <table size>`. Functions already in
C are missing from asm/, so existing rows are kept and new ones are added;
the file is committed so later tools don't depend on asm/. Functions with real
names (config/symbol_addrs.txt) are included too.
"""
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from binaries import BINARIES  # noqa: E402

FUNC_RE = re.compile(r"^glabel (\w+)\n(.*?)^endlabel \1\n", re.M | re.S)
TABLE_RE = re.compile(r"^dlabel (jtbl_([0-9A-F]{8}))\n(.*?)^enddlabel \1\n", re.M | re.S)


def main():
    b = BINARIES[sys.argv[1] if len(sys.argv) > 1 else "main"]
    out = b["jtbls"]
    sizes = {}
    for path in glob.glob(f"{b['asm_data']}/*.rodata.s"):
        for m in TABLE_RE.finditer(open(path).read()):
            words = re.findall(r"^\s*/\*.*\*/\s*\.word\s+(\S+)", m.group(3), re.M)
            # splat keeps the 16-byte alignment padding after a table inside its
            # label; real entries are code addresses, never zero, so drop it.
            while words and words[-1] == "0x00000000":
                words.pop()
            sizes[int(m.group(2), 16)] = 4 * len(words)
    names = {}
    for sym_path in glob.glob("config/symbol_addrs*.txt"):
        names.update({m.group(1): int(m.group(2), 16) for m in re.finditer(
            r"^(\w+)\s*=\s*0x([0-9A-Fa-f]+);\s*//\s*type:func", open(sym_path).read(), re.M)})
    rows = set()
    if os.path.exists(out):
        for line in open(out):
            if line.strip() and not line.startswith("#"):
                f, a, z = line.split()
                rows.add((int(f, 16), int(a, 16), int(z, 16)))
    known = {(f, a) for f, a, _ in rows}
    for path in glob.glob(f"{b['asm_code']}/*.s"):
        for m in FUNC_RE.finditer(open(path).read()):
            name = m.group(1)
            func = int(name[5:], 16) if re.fullmatch(r"func_[0-9A-F]{8}", name) else names.get(name)
            if func is None:
                continue
            for t in set(re.findall(r"%lo\(jtbl_([0-9A-F]{8})\)", m.group(2))):
                addr = int(t, 16)
                if (func, addr) not in known:
                    rows.add((func, addr, sizes[addr]))
    with open(out, "w") as f:
        f.write("# function table_address table_size  (generated by tools/make_jtbl_index.py)\n")
        for func, addr, size in sorted(rows):
            f.write(f"{func:08X} {addr:08X} {size:X}\n")
    print(f"{len(rows)} tables in {len({r[0] for r in rows})} functions")


if __name__ == "__main__":
    main()

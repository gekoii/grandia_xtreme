#!/usr/bin/env python3
"""Find address halves in asm that splat left as numbers, and write the
config/reloc_addrs entries that make them symbolic.

Usage: find_hilo.py <binary> [--write]

splat pairs a `lui` with the `%lo` uses of its register when it can follow
them. When it can't (the lui is in a delay slot, before a branch, hoisted out
of a loop into a saved register), both halves stay numbers:

    lui   $fp, (0x4B0000 >> 16)
    ...
    lw    $v1, -0x6BD8($fp)          # 0x004A9428, ptyCharData

and the reference doesn't move when the layout does. This follows each such
lui through its function (both ways at every branch, until the register is
written again) to the loads, stores and addius that use it as a base, takes
the label that contains the lowest address reached, and prints a
MIPS_HI16 entry for the lui and a MIPS_LO16 entry for each use:

    rom:0x03C0E8 reloc:MIPS_HI16 symbol:ptyCharData
    rom:0x03C324 reloc:MIPS_LO16 symbol:ptyCharData

If a use already has a %lo (the lui is an alternative path to a paired one),
its symbol is used. Only luis whose upper half falls in a binary we build
(0x0040-0x0075) are considered. With --write the entries replace the
generated block of config/reloc_addrs[.<binary>].txt; then run split.sh and
make (the build must still match, which checks the arithmetic) and
tools/shift_test.py. Labels come from the asm (tools/c_syms.py's index) and,
for main-executable addresses in an overlay, from build/SLUS_204.17.elf.
"""
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from binaries import BINARIES  # noqa: E402
from c_syms import LabelIndex, in_memory, symbol_file_names  # noqa: E402

INSN_RE = re.compile(r"/\*\s+([0-9A-F]+)\s+([0-9A-F]{8})\s+([0-9A-F]{8})\s+\*/\s+(\S+)\s*(.*)$")
LABEL_RE = re.compile(r"^\s*(?:jlabel\s+)?\.L([0-9A-F]{8})\b")
JLABEL_RE = re.compile(r"^\s*jlabel\s+\.L([0-9A-F]{8})\b")
FUNC_RE = re.compile(r"^\s*glabel\s+\w+")
LUI_RAW_RE = re.compile(r"^\$(\w+),\s*\((0x[0-9A-F]+) >> 16\)$")
LUI_SYM_RE = re.compile(r"^\$(\w+),\s*%hi\(([^)]+)\)$")
COPY_RE = re.compile(r"^\$(\w+),\s*\$(\w+),\s*\$(\w+)$")
COPY_OPS = {"daddu", "addu", "or", "move"}
MEM_RE = re.compile(r"^\$(\w+),\s*(.+)\(\$(\w+)\)$")
STORES = {"sb", "sh", "sw", "sd", "sq", "swc1", "sdc1", "swl", "swr", "sdl", "sdr", "sqc2", "lqc2"}
CALLER_SAVED = {f"t{i}" for i in range(10)} | {f"a{i}" for i in range(4)} | {"v0", "v1", "at"}
UNCOND = {"b", "j"}
BEGIN = "// BEGIN generated by tools/find_hilo.py"
END = "// END generated by tools/find_hilo.py"


def sext16(x):
    return x - 0x10000 if x & 0x8000 else x


def parse_imm(s):
    s = s.strip()
    m = re.fullmatch(r"\((0x[0-9A-Fa-f]+) & 0xFFFF\)", s)
    if m:
        return int(m.group(1), 16) & 0xFFFF
    neg = s.startswith("-")
    s = s.lstrip("-")
    if not re.fullmatch(r"0x[0-9A-Fa-f]+|\d+", s):
        return None
    v = int(s, 0)
    return -v if neg else v


def functions(path):
    """Instruction lists per asm file: [(rom, vram, op, args)], label -> index,
    and the jump-table labels and function starts (indexes)."""
    insns, labels = [], {}
    functions.jlabels, functions.starts = [], []
    for line in open(path):
        m = LABEL_RE.match(line)
        if m:
            labels[int(m.group(1), 16)] = len(insns)
        if JLABEL_RE.match(line):
            functions.jlabels.append(len(insns))
        if FUNC_RE.match(line):
            functions.starts.append(len(insns))
        m = INSN_RE.search(line)
        if m:
            insns.append((int(m.group(1), 16), int(m.group(2), 16), m.group(4), m.group(5).strip(),
                          int.from_bytes(bytes.fromhex(m.group(3)), "little")))
    return insns, labels


def branch_target(args):
    m = re.search(r"\.L([0-9A-F]{8})$", args)
    return int(m.group(1), 16) if m else None


def writes(op, args, reg):
    """Whether the instruction writes register `reg`."""
    if op in STORES or op.startswith("b") or op in ("j", "jr", "sync", "syscall", "nop"):
        return False
    m = re.match(r"^\$(\w+)", args)
    return bool(m and m.group(1) == reg)


def reload(op, args, reg, insns):
    """A load of reg from a stack slot the function also stores reg to: the
    compiler spilled the register around a call (sq/lq on the EE)."""
    m = re.fullmatch(r"\$(\w+),\s*(\S+)\(\$sp\)", args)
    if not (m and m.group(1) == reg and op in ("lq", "ld", "lw")):
        return False
    store = {"lq": "sq", "ld": "sd", "lw": "sw"}[op]
    return any(o == store and a == args for _, _, o, a, _ in insns)


JTBLS = {}


def load_jtbls(b):
    """Case labels of every jump table in the binary's asm data: name -> [addr]."""
    JTBLS.clear()
    name = None
    for path in glob.glob(f"asm/{b}/data/**/*.s", recursive=True):
        for line in open(path):
            m = re.match(r"\s*dlabel\s+(jtbl_\w+)", line)
            if m:
                name = m.group(1)
                JTBLS[name] = []
                continue
            if name and re.match(r"\s*enddlabel", line):
                name = None
                continue
            if name:
                m = re.search(r"\.word\s+\.L([0-9A-F]{8})\b", line)
                if m:
                    JTBLS[name].append(int(m.group(1), 16))


def switch_cases(insns, labels, i):
    """Instruction indexes of the case labels of the switch whose `jr` is at i,
    from the jump table its address is built from (a %lo(jtbl_...) just before)."""
    for k in range(i - 1, max(i - 16, -1), -1):
        m = re.search(r"%lo\((jtbl_\w+)\)", insns[k][3])
        if m:
            addrs = JTBLS.get(m.group(1))
            if not addrs or any(a not in labels for a in addrs):
                return None
            return sorted({labels[a] for a in addrs})
    return None


def follow(insns, labels, start, reg, _done=None):
    """Uses of reg as a base after the lui at index start: [(index, offset text)].

    Walks every path (both ways at branches, every case after a switch's
    `jr`) until reg is written again. A call clobbers a caller-saved reg
    until the function reloads it from the stack slot it spilled it to.
    A copy of reg into another register (`daddu $s4, $v0, $zero`) is
    followed too: the compiler keeps a %hi in a saved register that way."""
    uses = {}
    copies = set()
    _done = set() if _done is None else _done
    seen = set()
    stack = [(start + 1, True)]
    # a lui in a branch's delay slot also reaches the branch target, and only
    # that if the branch is unconditional
    if start > 0:
        op, args = insns[start - 1][2], insns[start - 1][3]
        if op.startswith("b") or op == "j":
            tgt = branch_target(args)
            if tgt is not None and tgt in labels:
                stack.append((labels[tgt], True))
            if op in UNCOND or (op == "beq" and args.startswith("$zero, $zero")):
                stack.pop(0)

    def step(i, live):
        """Effect of instruction i on reg: new live state, or None to end the path."""
        op, args = insns[i][2], insns[i][3]
        if live:
            m = MEM_RE.match(args)
            if m and m.group(3) == reg:
                uses[i] = m.group(2)
            elif op in ("addiu", "daddiu"):
                parts = [p.strip() for p in args.split(",")]
                if len(parts) == 3 and parts[1] == f"${reg}":
                    uses[i] = parts[2]
            elif op in COPY_OPS:
                c = COPY_RE.match(args)
                if c and c.group(1) != reg and sorted(c.group(2, 3)) == sorted((reg, "zero")):
                    copies.add((i, c.group(1)))
        if reload(op, args, reg, insns):
            return True
        if writes(op, args, reg):
            return None
        return live

    while stack:
        i, live = stack.pop()
        while 0 <= i < len(insns) and (i, live) not in seen:
            seen.add((i, live))
            op, args = insns[i][2], insns[i][3]
            live = step(i, live)
            if live is None:
                break
            if op in ("jal", "jalr", "jr") or op.startswith("b") or op == "j":
                # the delay slot runs before the jump
                if i + 1 < len(insns):
                    seen.add((i + 1, live))
                    live = step(i + 1, live)
                    if live is None:
                        break
                if op in ("jal", "jalr"):
                    if reg in CALLER_SAVED:
                        live = False
                    i += 2
                    continue
                if op == "jr":
                    if args != "$ra":
                        # a switch: its jump table's case labels follow (every
                        # case label of this function if the table isn't found)
                        cases = switch_cases(insns, labels, i)
                        if cases is None:
                            lo = max([x for x in functions.starts if x <= i], default=0)
                            hi = min([x for x in functions.starts if x > i], default=len(insns))
                            cases = [j for j in functions.jlabels if lo <= j < hi]
                        stack.extend((j, live) for j in cases)
                    break
                tgt = branch_target(args)
                if tgt is not None and tgt in labels:
                    stack.append((labels[tgt], live))
                if op in UNCOND or (op == "beq" and args.startswith("$zero, $zero")):
                    break
                i += 2
                continue
            i += 1
    for i, r in sorted(copies):
        if (i, r) not in _done:
            _done.add((i, r))
            for j, t in follow(insns, labels, i, r, _done):
                uses.setdefault(j, t)
    return sorted(uses.items())


class Symbols:
    """Containing label for an address: the binary's own asm labels, or the
    main executable's for an overlay."""

    def __init__(self, b):
        self.b = b
        self.own = LabelIndex(b)
        self.main = LabelIndex("main") if b != "main" else self.own

    def address(self, name):
        if not hasattr(self, "_addrs"):
            self._addrs = symbol_file_names(sorted(glob.glob("config/symbol_addrs*.txt")))
            for idx in (self.main, self.own):
                for a, n, _ in idx.labels:
                    self._addrs.setdefault(n, a)
        return self._addrs.get(name)

    def resolve(self, addr):
        for name, idx in ((self.b, self.own), ("main", self.main)):
            if in_memory(name, addr):
                r = idx.resolve(None, addr)
                if r:
                    return r
        return None


def scan(b):
    syms = Symbols(b)
    load_jtbls(b)
    entries, notes = [], []
    for path in sorted(glob.glob(f"asm/{b}/{b}/*.s")):
        insns, labels = functions(path)
        for i, (rom, vram, op, args, word) in enumerate(insns):
            if op != "lui":
                continue
            m = LUI_RAW_RE.match(args)
            if not m:
                ms = LUI_SYM_RE.match(args)
                if ms:
                    symbolic(insns, labels, i, ms.group(1), ms.group(2), word & 0xFFFF, path, syms, entries, notes)
                continue
            hi = int(m.group(2), 16) >> 16
            if not 0x0040 <= hi <= 0x0075:
                continue
            reg = m.group(1)
            uses = follow(insns, labels, i, reg)
            if not uses:
                notes.append(f"{vram:08X} lui ${reg}, {hi:#x}: no use found ({path})")
                continue
            known = [u for u in uses if u[1].startswith("%lo(")]
            raw = [(j, parse_imm(t)) for j, t in uses if not t.startswith("%lo(")]
            if any(lo is None for _, lo in raw):
                notes.append(f"{vram:08X} lui ${reg}, {hi:#x}: a use isn't a plain offset ({path})")
                continue
            if known:
                sym_text = re.match(r"%lo\(([^)]+)\)", known[0][1]).group(1)
                mm = re.fullmatch(r"(\S+?)(?:\s*\+\s*(0x[0-9A-Fa-f]+))?", sym_text.replace(" ", ""))
                base, base_add = mm.group(1), int(mm.group(2), 16) if mm.group(2) else 0
                if raw:
                    notes.append(f"{vram:08X} lui ${reg}, {hi:#x}: mixes %lo({sym_text}) with raw uses ({path})")
                    continue
                entries.append((rom, "MIPS_HI16", base, base_add, f"{vram:08X} (as at {insns[known[0][0]][1]:08X})"))
                continue
            targets = [(hi << 16) + sext16(lo & 0xFFFF) for _, lo in raw]
            r = syms.resolve(min(targets))
            if r is None:
                notes.append(f"{vram:08X} lui ${reg}, {hi:#x}: no label contains {min(targets):08X} ({path})")
                continue
            base, off0 = r
            base_addr = min(targets) - off0
            first = targets[0] - base_addr
            entries.append((rom, "MIPS_HI16", base, first, f"{vram:08X}"))
            for (j, lo), t in zip(raw, targets):
                entries.append((insns[j][0], "MIPS_LO16", base, t - base_addr, f"{insns[j][1]:08X} -> {t:08X}"))
    return entries, notes


def symbolic(insns, labels, i, reg, sym_text, hi, path, syms, entries, notes):
    """A lui splat did make %hi(sym): its uses that splat left as numbers
    (often through a copy in a saved register) get MIPS_LO16 entries for
    the same symbol, with the addend the number implies."""
    vram = insns[i][1]
    uses = follow(insns, labels, i, reg)
    raw = [(j, parse_imm(t)) for j, t in uses if not t.startswith("%lo(")]
    if not raw:
        return
    if any(lo is None for _, lo in raw):
        notes.append(f"{vram:08X} lui ${reg}, %hi({sym_text}): a use isn't a plain offset ({path})")
        return
    mm = re.fullmatch(r"(\S+?)(?:\+(-?0x[0-9A-Fa-f]+|-?\d+))?", sym_text.replace(" ", ""))
    base, add = mm.group(1), int(mm.group(2), 0) if mm.group(2) else 0
    addr = syms.address(base)
    if addr is None:
        notes.append(f"{vram:08X} lui ${reg}, %hi({sym_text}): address of {base} unknown ({path})")
        return
    want = ((addr + add + 0x8000) >> 16) & 0xFFFF
    if want != hi:
        notes.append(f"{vram:08X} lui ${reg}, %hi({sym_text}) is {hi:#x}, expected {want:#x} ({path})")
        return
    targets = [(j, (hi << 16) + sext16(lo & 0xFFFF)) for j, lo in raw]
    # The register can't hold %hi(sym) at a use whose address isn't in sym's
    # object (the walk took a path where it holds something else, e.g. a
    # reload from a stack slot reused for another value): leave those.
    good = []
    for j, t in targets:
        r = syms.resolve(t)
        if r is None or r[0] != base:
            notes.append(f"{insns[j][1]:08X}: use of lui ${reg}, %hi({sym_text}) at {vram:08X} reaches {t:08X}, "
                         f"{'in ' + r[0] if r else 'no label'}: left alone ({path})")
            continue
        good.append((j, t))
    for j, t in good:
        entries.append((insns[j][0], "MIPS_LO16", base, t - addr, f"{insns[j][1]:08X} -> {t:08X} (lui %hi({sym_text}) at {vram:08X})"))


def reloc_file(b):
    return "config/reloc_addrs.txt" if b == "main" else f"config/reloc_addrs.{b}.txt"


def main():
    if len(sys.argv) < 2 or sys.argv[1] not in BINARIES:
        raise SystemExit(__doc__)
    b = sys.argv[1]
    entries, notes = scan(b)
    lines = []
    seen = set()
    for rom, typ, sym, add, why in sorted(entries):
        if rom in seen:
            continue
        seen.add(rom)
        a = f" addend:0x{add:X}" if add > 0 else f" addend:-0x{-add:X}" if add < 0 else ""
        lines.append(f"rom:0x{rom:06X} reloc:{typ} symbol:{sym}{a} // {why}")
    for n in notes:
        print("note:", n)
    print(f"{b}: {sum(1 for e in entries if e[1] == 'MIPS_HI16')} luis, {len(lines)} entries")
    if "--write" not in sys.argv:
        print("\n".join(lines))
        return
    path = reloc_file(b)
    text = open(path).read() if os.path.exists(path) else ""
    # Keep what earlier runs found: once split.sh has applied an entry, its
    # lui is symbolic and isn't found again.
    if BEGIN in text:
        old = text[text.index(BEGIN):text.index(END)].splitlines()[1:]
        have = {re.match(r"rom:(0x[0-9A-F]+)", l).group(1) for l in lines}
        lines = sorted(lines + [l for l in old if l.startswith("rom:") and
                                re.match(r"rom:(0x[0-9A-F]+)", l).group(1) not in have])
    block = f"{BEGIN}: %hi/%lo halves splat left as numbers\n" + "\n".join(lines) + f"\n{END}\n"
    if BEGIN in text:
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", lambda _: block, text, flags=re.S)
    else:
        text = text.rstrip("\n") + "\n\n" + block
    open(path, "w").write(text)
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
